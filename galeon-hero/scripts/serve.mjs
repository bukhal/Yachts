// Zero-dependency static server for the demo: `npm start` → http://127.0.0.1:4317
// Also exposes POST /__dev/fx-defaults, used by "Tune effects → Save as defaults"
// to write src/config/fx-tuned.js. Bound to 127.0.0.1 only.
import http from "node:http";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { sanitizeFx, diffFromFactory } from "../src/fx/store.js";
import { buildFactoryDefaults } from "../src/config/fx-defaults.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const port = Number(process.env.PORT) || 4317;
const tunedFile = path.join(root, "src/config/fx-tuned.js");
const types = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".png": "image/png", ".svg": "image/svg+xml", ".woff2": "font/woff2", ".json": "application/json", ".ts": "text/plain; charset=utf-8",
  ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".webp": "image/webp", ".avif": "image/avif", ".mp4": "video/mp4", ".webm": "video/webm", ".md": "text/plain; charset=utf-8",
};
// Only pages served by this server may call the dev endpoint (a page on another
// site could otherwise POST a simple request and overwrite fx-tuned.js).
const isLocalOrigin = (origin) => !origin || /^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/.test(origin);

async function saveDefaults(req, res) {
  let body = "";
  for await (const chunk of req) {
    body += chunk;
    if (body.length > 64_000) return res.writeHead(413).end();
  }
  let raw;
  try {
    raw = JSON.parse(body);
  } catch {
    return res.writeHead(400).end("Invalid JSON");
  }
  // Clamp to the schema, then keep only what differs from factory values.
  const tuned = diffFromFactory(sanitizeFx(raw, buildFactoryDefaults()));
  const source = `// Generated by "Tune effects → Save as defaults" (dev server only).
// Holds just the values that differ from the factory defaults in fx-defaults.js.
// Edit by hand or delete the entries to fall back to factory values.
// Saved ${new Date().toISOString()}
export const TUNED = ${JSON.stringify(tuned, null, 2)};
`;
  await fs.writeFile(tunedFile, source);
  res.writeHead(200, { "content-type": "application/json" }).end(JSON.stringify({ file: "src/config/fx-tuned.js", tuned }));
}

http.createServer(async (req, res) => {
  const url = new URL(req.url, "http://localhost");
  if (url.pathname === "/__dev/fx-defaults") {
    if (req.method !== "POST") return res.writeHead(405).end();
    if (!isLocalOrigin(req.headers.origin)) return res.writeHead(403).end();
    return saveDefaults(req, res).catch((e) => res.writeHead(500).end(String(e.message)));
  }
  let pathname;
  try {
    pathname = decodeURIComponent(url.pathname);
  } catch {
    return res.writeHead(400).end("Bad request"); // malformed %-escape must not kill the server
  }
  let file = path.join(root, pathname);
  if (file !== root && !file.startsWith(root + path.sep)) return res.writeHead(403).end();
  if (url.pathname.endsWith("/")) file = path.join(file, "index.html");
  try {
    const body = await fs.readFile(file);
    res.writeHead(200, { "content-type": types[path.extname(file)] ?? "application/octet-stream", "cache-control": "no-cache" });
    res.end(body);
  } catch {
    res.writeHead(404).end("Not found");
  }
}).listen(port, "127.0.0.1", () => console.log(`Galeon hero demo → http://127.0.0.1:${port}`));
